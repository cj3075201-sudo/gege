using System;
using System.Collections.Generic;
using UnityEngine;

namespace DeliveryRider
{
    // One place a hazard of one type may be spawned, baked from the road splines by the hazard installer.
    [Serializable]
    public struct HazardCandidate
    {
        public string type;
        [Tooltip("Index of the road spot this candidate belongs to (shares its route list).")]
        public int spot;
        public Vector3 position;
        public Quaternion rotation;
        [Tooltip("Half width of the carriageway at the spot.")]
        public float halfWidth;
        [Tooltip("Which side of the road (+1 right, -1 left of the baked direction).")]
        public int side;
        public bool alley;
        [Tooltip("Pigeon only: escape against the baked direction.")]
        public bool flip;
    }

    // Every candidate place for every hazard type, plus the delivery routes passing each road spot.
    // Regenerated by Delivery Rider -> Apply Hazard Spawning; never edited by hand.
    public sealed class HazardCandidates : ScriptableObject
    {
        [Serializable]
        public sealed class Spot
        {
            public Vector3 position;
            [Tooltip("Call routes (shop index x door count + door index) that pass within 7 m.")]
            public int[] routes = Array.Empty<int>();
        }

        [Serializable]
        public sealed class RoutePath
        {
            public Vector3[] points = Array.Empty<Vector3>();
            public Vector3[] mainPoints = Array.Empty<Vector3>();
        }
        [SerializeField] private RoutePath[] routePaths = Array.Empty<RoutePath>();
        public IReadOnlyList<RoutePath> RoutePaths => routePaths;
        public void ConfigureRoutes(RoutePath[] value) => routePaths = value ?? Array.Empty<RoutePath>();

        public float RouteDistance(int route, Vector3 point, bool shortestOnly = false)
        {
            if (route < 0 || route >= routePaths.Length) return float.PositiveInfinity;
            float distance = Distance(routePaths[route].points, point);
            return shortestOnly ? distance : Mathf.Min(distance, Distance(routePaths[route].mainPoints, point));
        }
        private static float Distance(Vector3[] path, Vector3 point)
        {
            float best = float.PositiveInfinity;
            for (int i = 1; i < path.Length; i++)
            {
                var a = path[i - 1]; var delta = path[i] - a; delta.y = 0f;
                var relative = point - a; relative.y = 0f;
                float t = delta.sqrMagnitude > 0f ? Mathf.Clamp01(Vector3.Dot(relative, delta) / delta.sqrMagnitude) : 0f;
                best = Mathf.Min(best, (relative - delta * t).magnitude);
            }
            return best;
        }
        [SerializeField] private Spot[] spots = Array.Empty<Spot>();
        [SerializeField] private HazardCandidate[] candidates = Array.Empty<HazardCandidate>();

        public IReadOnlyList<HazardCandidate> Candidates => candidates;
        public IReadOnlyList<Spot> Spots => spots;
        public int[] Routes(int spot) => spot >= 0 && spot < spots.Length ? spots[spot].routes : Array.Empty<int>();

        public void Configure(Spot[] roadSpots, HazardCandidate[] places)
        {
            spots = roadSpots;
            candidates = places;
        }
    }
}
